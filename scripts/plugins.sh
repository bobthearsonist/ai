#!/usr/bin/env bash
# Choose which copy of each plugin Claude Code and Copilot CLI load, from the
# `dev_marketplace:` and `plugins:` keys in local.yaml. See docs/plugins.md.
#
#   mode: dev        load the working copy in place from the dev marketplace,
#                    so edits reach the next session without publishing
#   mode: published  install the copy from the plugin's own marketplace
#
# Both clients let a plugin shadow a same-named one, so every other copy of a
# plugin is disabled, in every Claude Code scope. Re-running only acts on
# differences. Written for bash 3.2 (macOS), so no associative arrays.
#
# Usage: ./scripts/plugins.sh [--dry-run]
set -euo pipefail

cd "$(dirname "$0")/.."
LOCAL_CONFIG="local.yaml"
# Marks the dev marketplace.json as generated, so a hand-written one is never overwritten.
GENERATED_BY="Generated by ai/scripts/plugins.sh from local.yaml; edits are overwritten."

dry_run=false
case "${1:-}" in
    --dry-run) dry_run=true ;;
    "") ;;
    *) echo "Usage: $0 [--dry-run]" >&2; exit 2 ;;
esac

failures=()

expand_home() {
    printf '%s\n' "${1/#\~/$HOME}"
}

# local.yaml may hold Windows paths (C:\Repositories); work with them in POSIX
# form here and hand native form to the CLIs.
posix_path() {
    if command -v cygpath >/dev/null 2>&1; then
        cygpath -u "$1"
    else
        printf '%s\n' "$1"
    fi
}

# Both CLIs record local marketplace paths in native form.
native_path() {
    if command -v cygpath >/dev/null 2>&1; then
        cygpath -w "$1"
    else
        printf '%s\n' "$1"
    fi
}

run() {
    if $dry_run; then
        echo "  would run: $*"
        return 0
    fi
    echo "  run: $*"
    "$@"
}

# Runs a client command, recording a failure instead of stopping the rest.
attempt() {
    if ! run "$@"; then
        failures+=("$*")
    fi
}

cfg() {
    yq e "$1" "$LOCAL_CONFIG"
}

plugin_cfg() {
    P="$1" yq e ".plugins[strenv(P)].$2 // \"\"" "$LOCAL_CONFIG"
}

contains() {
    local needle="$1" item
    shift
    for item in "$@"; do
        [[ "$item" == "$needle" ]] && return 0
    done
    return 1
}

if [[ ! -f "$LOCAL_CONFIG" ]]; then
    echo "No local.yaml found."
    exit 0
fi
plugin_names=$(cfg '.plugins // {} | keys | .[]')
if [[ -z "$plugin_names" ]]; then
    echo "No plugins in local.yaml."
    exit 0
fi

dev_name=$(cfg '.dev_marketplace.name // "local"')
dev_root=$(cfg '.dev_marketplace.root // ""')
[[ -n "$dev_root" ]] && dev_root=$(posix_path "$(expand_home "$dev_root")")

# === Dev marketplace ===
# Lists every plugin that has a `path`, whatever its mode, so moving a plugin to
# dev later is only a mode change.
echo "=== Dev marketplace ==="
dev_listed=()
manifest=$(mktemp)
trap 'rm -f "$manifest"' EXIT
N="$dev_name" D="$GENERATED_BY" yq -n \
    '.name = strenv(N) | .owner.name = "local" | .description = strenv(D) | .plugins = []' > "$manifest"

for name in $plugin_names; do
    path=$(plugin_cfg "$name" path)
    [[ -z "$path" ]] && continue
    if [[ -z "$dev_root" ]]; then
        echo "  ⚠️  $name has a path but dev_marketplace.root is not set — not listed"
        continue
    fi
    plugin_json="$dev_root/$path/.claude-plugin/plugin.json"
    if [[ ! -f "$plugin_json" ]]; then
        echo "  ⚠️  $name: $plugin_json not found — not listed"
        continue
    fi
    description=$(yq -p=json -oy '.description // ""' "$plugin_json")
    N="$name" S="./$path" D="$description" yq -i \
        '.plugins += [{"name": strenv(N), "source": strenv(S), "description": strenv(D)}]' "$manifest"
    dev_listed+=("$name")
done

dev_manifest="$dev_root/.claude-plugin/marketplace.json"
if (( ${#dev_listed[@]} == 0 )); then
    echo "  (no plugin has a usable path)"
else
    new_json=$(yq -o=json '.' "$manifest")
    if [[ -f "$dev_manifest" && "$(yq -p=json -oy '.description // ""' "$dev_manifest")" != "$GENERATED_BY" ]]; then
        echo "  ⚠️  $dev_manifest was not written by this script — leaving it alone"
        failures+=("dev marketplace at $dev_root")
        dev_listed=()
    elif [[ -f "$dev_manifest" && "$(cat "$dev_manifest")" == "$new_json" ]]; then
        echo "  = $dev_manifest is up to date (${dev_listed[*]})"
    elif $dry_run; then
        echo "  would write $dev_manifest:"
        printf '%s\n' "$new_json" | sed 's/^/    /'
    else
        mkdir -p "$(dirname "$dev_manifest")"
        printf '%s\n' "$new_json" > "$dev_manifest"
        echo "  → wrote $dev_manifest (${dev_listed[*]})"
    fi
fi

# === Which copy each plugin should load ===
plan_names=()
plan_ids=()
for name in $plugin_names; do
    mode=$(plugin_cfg "$name" mode)
    case "${mode:-published}" in
        dev)
            if contains "$name" ${dev_listed[@]+"${dev_listed[@]}"}; then
                plan_names+=("$name")
                plan_ids+=("$name@$dev_name")
            else
                echo "⚠️  $name: mode dev, but it is not in the dev marketplace — skipped"
                failures+=("$name (dev copy unavailable)")
            fi
            ;;
        published)
            marketplace=$(plugin_cfg "$name" marketplace)
            if [[ -n "$marketplace" ]]; then
                plan_names+=("$name")
                plan_ids+=("$name@$marketplace")
            else
                echo "⚠️  $name: mode published needs a marketplace — skipped"
                failures+=("$name (no marketplace)")
            fi
            ;;
        *)
            echo "⚠️  $name: unknown mode '$mode' — skipped"
            failures+=("$name (mode $mode)")
            ;;
    esac
done

# Adds the marketplace a wanted id comes from when the client lacks it.
# $1 client, $2 registered names (one per line), $3 wanted id, $4 plugin name.
ensure_marketplace() {
    local client="$1" registered="$2" id="$3" name="$4" marketplace source
    marketplace="${id#*@}"
    grep -qxF "$marketplace" <<< "$registered" && return 0
    if [[ "$marketplace" == "$dev_name" ]]; then
        source=$(native_path "$dev_root")
    else
        source=$(plugin_cfg "$name" marketplace_source)
    fi
    if [[ -z "$source" ]]; then
        echo "  ⚠️  $client has no marketplace '$marketplace' and $name has no marketplace_source"
        failures+=("$client: marketplace $marketplace")
        return 1
    fi
    attempt "$client" plugin marketplace add "$source"
}

# === Claude Code ===
# The wanted copy is installed at user scope. Other copies are disabled in
# whichever scope enabled them; project and local scopes must run from their
# project folder.
claude_config_args=()
claude_copy_config() {
    local name="$1" want="$2" settings="$HOME/.claude/settings.json" kv
    claude_config_args=()
    [[ -f "$settings" ]] || return 0
    # Carry plugin options over from another copy, since they are stored per plugin id.
    while IFS= read -r kv; do
        [[ -n "$kv" ]] && claude_config_args+=(--config "$kv")
    done < <(N="$name" W="$want" yq -p=json -oy '.pluginConfigs // {} | to_entries
        | map(select((.key | split("@") | .[0]) == strenv(N) and .key != strenv(W)))
        | (.[0].value.options // {}) | to_entries | .[] | .key + "=" + (.value | tostring)' "$settings")
}

setup_claude() {
    local installed registered i name want state id scope project
    echo "=== Claude Code ==="
    installed=$(claude plugin list --json)
    registered=$(claude plugin marketplace list --json | yq -p=json -oy '.[].name')

    for i in "${!plan_names[@]}"; do
        name="${plan_names[$i]}"
        want="${plan_ids[$i]}"
        ensure_marketplace claude "$registered" "$want" "$name" || continue

        state=$(W="$want" yq -p=json -oy '.[] | select(.id == strenv(W) and .scope == "user") | .enabled' <<< "$installed")
        case "$state" in
            true) echo "  = $want enabled" ;;
            false) attempt claude plugin enable "$want" --scope user ;;
            *)
                claude_copy_config "$name" "$want"
                attempt claude plugin install "$want" --scope user ${claude_config_args[@]+"${claude_config_args[@]}"}
                ;;
        esac

        # Disable other copies one at a time, re-reading the list after each: two
        # scopes can share a settings file (a project scope rooted at $HOME uses
        # ~/.claude/settings.json), so one disable may already cover the next.
        local attempted=$'\n' line candidate id scope project
        while :; do
            line=""
            while IFS= read -r candidate; do
                [[ -z "$candidate" || "$attempted" == *$'\n'"$candidate"$'\n'* ]] && continue
                line="$candidate"
                break
            done < <(N="$name" W="$want" yq -p=json -o=tsv '.[]
                | select((.id | split("@") | .[0]) == strenv(N) and .id != strenv(W) and .enabled == true)
                | [.id, .scope, (.projectPath // "")]' <<< "$installed")
            [[ -z "$line" ]] && break
            attempted+="$line"$'\n'
            IFS=$'\t' read -r id scope project <<< "$line"
            if [[ "$scope" == "user" ]]; then
                attempt claude plugin disable "$id" --scope user
            else
                echo "  (in $project)"
                if ! (cd "$project" && run claude plugin disable "$id" --scope "$scope"); then
                    failures+=("claude plugin disable $id --scope $scope in $project")
                fi
            fi
            $dry_run || installed=$(claude plugin list --json)
        done
    done
}

# === Copilot CLI ===
# Copilot records enabled state per plugin id in ~/.copilot/settings.json.
setup_copilot() {
    local settings="$HOME/.copilot/settings.json" registered i name want state id
    echo "=== Copilot CLI ==="
    registered=$(copilot plugin marketplace list --json | yq -p=json -oy '.[].name')

    for i in "${!plan_names[@]}"; do
        name="${plan_names[$i]}"
        want="${plan_ids[$i]}"
        ensure_marketplace copilot "$registered" "$want" "$name" || continue

        # tostring keeps false distinct from missing; yq's // treats both alike.
        state=null
        [[ -f "$settings" ]] && state=$(W="$want" yq -p=json -oy '(.enabledPlugins // {})[strenv(W)] | tostring' "$settings")
        case "$state" in
            true) echo "  = $want enabled" ;;
            false) attempt copilot plugin enable "$want" ;;
            *) attempt copilot plugin install "$want" ;;
        esac

        [[ -f "$settings" ]] || continue
        while IFS= read -r id; do
            [[ -n "$id" ]] && attempt copilot plugin disable "$id"
        done < <(N="$name" W="$want" yq -p=json -oy '.enabledPlugins // {} | to_entries | .[]
            | select((.key | split("@") | .[0]) == strenv(N) and .key != strenv(W) and .value == true) | .key' "$settings")
    done
}

if (( ${#plan_names[@]} )); then
    if command -v claude >/dev/null 2>&1; then
        setup_claude
    else
        echo "=== Claude Code === (not installed — skipped)"
    fi
    if command -v copilot >/dev/null 2>&1; then
        setup_copilot
    else
        echo "=== Copilot CLI === (not installed — skipped)"
    fi
fi

if (( ${#failures[@]} )); then
    echo "Done with errors:"
    printf '  - %s\n' "${failures[@]}"
    exit 1
fi
if $dry_run; then
    echo "Dry run — nothing changed."
else
    echo "Done. New sessions load these copies; in a running Claude Code session use /reload-plugins."
fi
